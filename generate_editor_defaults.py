"""
Builds siteresources/defaults.js for the static settings editor from
config_schema.py and permissions.py, so the editor and the bot always agree
on defaults, limits and the command list. Run it after changing either:

    python3 generate_editor_defaults.py
"""

import json

import config_schema as cs
import permissions

OUTPUT = "siteresources/defaults.js"

def main():
    data = {
        "schema": cs.SCHEMA_VERSION,
        "maxImportBytes": cs.MAX_IMPORT_BYTES,
        "defaults": cs.DEFAULT_CONFIG,
        "embedDefault": cs.EMBED_DEFAULT,
        "rolemenuDefault": cs.ROLEMENU_DEFAULT,
        "rolemenuOptionDefault": cs.ROLEMENU_OPTION_DEFAULT,
        "postDefault": cs.POST_DEFAULT,
        "overrideDefault": cs.OVERRIDE_DEFAULT,
        "logEvents": cs.LOG_EVENTS,
        "logCategories": cs.LOG_CATEGORIES,
        "automodActions": cs.AUTOMOD_ACTIONS,
        "honeypotActions": cs.HONEYPOT_ACTIONS,
        "honeypotDelete": cs.HONEYPOT_DELETE,
        "rolemenuModes": cs.ROLEMENU_MODES,
        "rolemenuTypes": cs.ROLEMENU_TYPES,
        "buttonStyles": cs.BUTTON_STYLES,
        "postableChannels": cs.POSTABLE_CHANNELS,
        "lockableChannels": cs.LOCKABLE_CHANNELS,
        "commands": permissions.COMMANDS,
    }
    with open(OUTPUT, "w") as f:
        f.write("// Generated by generate_editor_defaults.py from config_schema.py + permissions.py - do not edit by hand.\n")
        f.write("window.RAFISOL = ")
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write(";\n")
    print(f"Wrote {OUTPUT}")

if __name__ == "__main__":
    main()
